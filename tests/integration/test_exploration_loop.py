"""Exploration loop integration tests (Section 2.2).

Tests the flow: Scenario activation -> Lab hypothesis -> Pattern discovery ->
Hypothesis ranking.

Validates:
1. Lab generates hypotheses from released data
2. Each hypothesis has falsification_tests
3. constraint_violation_report labeled "预筛结果，非权威"
4. Lab isolation verified
"""

from __future__ import annotations

import pytest
from httpx import AsyncClient

pytestmark = pytest.mark.integration


async def test_lab_generates_hypotheses(api_client: AsyncClient) -> None:
    """Lab generates hypotheses from released constraint data."""
    constraints = [
        {
            "constraint_id": "cc-temp-limit",
            "scenario_criticality": "safety_critical",
            "validation": {
                "type": "range",
                "config": {"variable": "temperature", "min": 0, "max": 100},
            },
        }
    ]
    data = {"state_variables": {"temperature": 65.3}}

    response = await api_client.post(
        "/api/v1/lab/explore/hypothesis",
        json={"data": data, "constraints": constraints},
    )
    assert response.status_code == 200
    result = response.json()
    assert "hypotheses" in result
    assert result["count"] >= 0


async def test_hypotheses_have_falsification_tests(
    api_client: AsyncClient,
) -> None:
    """Each hypothesis generated by Lab must have falsification_tests."""
    constraints = [
        {
            "constraint_id": "cc-temp-limit",
            "scenario_criticality": "operational",
            "validation": {
                "type": "range",
                "config": {"variable": "temperature", "min": 10, "max": 90},
            },
        }
    ]
    data = {"state_variables": {"temperature": 50.0}}

    response = await api_client.post(
        "/api/v1/lab/explore/hypothesis",
        json={"data": data, "constraints": constraints},
    )
    assert response.status_code == 200
    result = response.json()
    for hyp in result["hypotheses"]:
        assert "falsification_tests" in hyp
        assert isinstance(hyp["falsification_tests"], list)


