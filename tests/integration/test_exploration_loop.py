async def test_lab_data_release_no_hidden_exposure(
    api_client: AsyncClient,
) -> None:
    """Data release endpoint never exposes hidden validation sets."""
    response = await api_client.get("/api/v1/lab/data-release/dp-test-001")
    assert response.status_code == 200
    result = response.json()
    assert result["hidden_exposure"] is False
    # The data itself should not contain hidden references
    data_str = str(result).lower()
    hidden_keywords = [
        "hidden_challenge_set",
        "hidden_validation_set",
        "audit_benchmark_reference",
        "production_acceptance_reference",
    ]
    for kw in hidden_keywords:
        assert kw not in data_str, f"Data release contains hidden reference: {kw}"


